"""Local-only fine-tuning/validation. Original glue: MIT, not Ultralytics.

Never imports Ultralytics for --help. Run only in an isolated, offline environment.
All inputs and outputs must be outside a Git checkout. No automatic installation.
"""
import argparse
import json
import os
from pathlib import Path
import socket

from common import loss_values, sha256, verify_freeze, write_json

VERSION = '8.4.189'
ALLOWED_HPARAMS = {
    'imgsz', 'epochs', 'batch', 'workers', 'seed', 'deterministic', 'optimizer',
    'lr0', 'lrf', 'weight_decay', 'patience', 'amp', 'cache', 'cos_lr', 'mosaic',
    'close_mosaic', 'mixup', 'degrees', 'translate', 'scale', 'fliplr', 'flipud',
    'hsv_h', 'hsv_s', 'hsv_v', 'perspective', 'shear', 'multi_scale',
}


def outside_checkout(path):
    path = Path(path).resolve()
    if any((parent / '.git').exists() for parent in (path, *path.parents)):
        raise ValueError('private_paths_must_be_outside_git')
    return path


def existing_file(path):
    path = outside_checkout(path)
    if not path.is_file():
        raise ValueError('local_input_file_required')
    return path


def disable_network():
    """Defense in depth, NOT an OS sandbox; use an egress-denied process too."""
    def denied(*args, **kwargs):
        raise RuntimeError('network_disabled_for_training')
    socket.getaddrinfo = denied
    socket.create_connection = denied
    socket.socket.connect = denied
    socket.socket.connect_ex = denied
    socket.socket.sendto = denied


def local_dataset(path):
    import yaml
    data = yaml.safe_load(path.read_text(encoding='utf-8'))
    allowed = {'path', 'train', 'val', 'test', 'names', 'nc'}
    if not isinstance(data, dict) or set(data) - allowed:
        raise ValueError('only_local_detection_yaml_fields_allowed')
    root = Path(data.get('path', ''))
    if not root.is_absolute() or not root.is_dir():
        raise ValueError('data_path_must_be_existing_absolute_directory')
    root = outside_checkout(root)
    data['path'] = str(root)
    if not data.get('names'):
        raise ValueError('class_names_required')
    for split in ('train', 'val', 'test'):
        value = data.get(split)
        if value is None and split == 'test':
            continue
        entries = value if isinstance(value, list) else [value]
        resolved = []
        for entry in entries:
            if not isinstance(entry, str) or '://' in entry:
                raise ValueError('local_split_path_required')
            target = (root / entry).resolve()
            if not target.is_relative_to(root) or not target.exists():
                raise ValueError('split_must_exist_inside_data_root')
            if target.is_file():
                if target.suffix != '.txt':
                    raise ValueError('split_file_must_be_local_image_list')
                lines = target.read_text(encoding='utf-8').splitlines()
                if not lines:
                    raise ValueError('empty_image_list')
                for line in lines:
                    # Mirror upstream ./-relative convention; require absolute otherwise.
                    image = target.parent / line[2:] if line.startswith('./') else Path(line)
                    if (not line or '://' in line or not image.is_absolute()
                            or not image.resolve().is_relative_to(root) or not image.is_file()):
                        raise ValueError('image_list_requires_existing_local_files')
            resolved.append(str(target))
        if not resolved:
            raise ValueError('empty_split')
        data[split] = resolved if isinstance(value, list) else resolved[0]
    # Freeze original data, including labels and private split metadata. Cache is
    # generated by upstream and excluded; cache=False does not prevent label caches.
    files = []
    for item in root.rglob('*'):
        if item.is_symlink():
            raise ValueError('dataset_symlinks_not_supported')
        if item.is_file() and item.suffix != '.cache':
            if not item.resolve().is_relative_to(root):
                raise ValueError('dataset_symlink_escape')
            files.append(item.resolve())
    if not files:
        raise ValueError('empty_dataset_root')
    return data, files


def configure_backend(output, threads):
    os.environ.update({
        'YOLO_CONFIG_DIR': str(output / 'settings'), 'YOLO_AUTOINSTALL': 'false',
        'YOLO_OFFLINE': 'true', 'WANDB_DISABLED': 'true', 'WANDB_MODE': 'disabled',
        'COMET_MODE': 'DISABLED', 'HF_HUB_OFFLINE': '1', 'DO_NOT_TRACK': '1',
        'OMP_NUM_THREADS': str(threads), 'MKL_NUM_THREADS': str(threads),
        'OPENBLAS_NUM_THREADS': '1',
    })
    disable_network()
    import ultralytics
    if ultralytics.__version__ != VERSION:
        raise RuntimeError('requires_ultralytics_' + VERSION)
    from ultralytics import settings
    settings.update({key: False for key in (
        'sync', 'clearml', 'comet', 'dvc', 'mlflow', 'raytune', 'tensorboard', 'wandb')})
    # Events/platform callbacks are added unconditionally in this pinned version.
    # Suppress ALL integration callbacks, leaving core local callbacks intact.
    import ultralytics.utils.callbacks as callbacks
    import ultralytics.utils.callbacks.base as callback_base
    callbacks.add_integration_callbacks = lambda instance: None
    callback_base.add_integration_callbacks = lambda instance: None
    # Upstream dataset validation tries fetching fonts even with plots=False.
    import ultralytics.data.utils as data_utils
    data_utils.check_font = lambda *args, **kwargs: None
    import torch
    import cv2
    torch.set_num_threads(threads)
    torch.set_num_interop_threads(1)
    cv2.setNumThreads(1)
    return ultralytics, torch


def check_head(validator):
    if not hasattr(validator, 'end2end') or bool(validator.end2end):
        raise RuntimeError('unexpected_or_unverifiable_end2end_head')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('mode', choices=('train', 'validate'))
    parser.add_argument('--family', choices=('yolo11n', 'yolo26n'), required=True)
    parser.add_argument('--data', type=Path, required=True)
    parser.add_argument('--weights', type=Path, required=True,
                        help='Trusted existing official pretrained .pt, or validation checkpoint')
    parser.add_argument('--hparams', type=Path, required=True)
    parser.add_argument('--freeze', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True, help='New private directory')
    parser.add_argument('--device', default='cpu', help='One device only; no DDP')
    parser.add_argument('--threads', type=int, default=2)
    parser.add_argument('--split', choices=('val', 'test'), default='val')
    args = parser.parse_args()
    if args.threads < 1 or ',' in args.device or args.device in ('', '-1'):
        raise ValueError('positive_threads_and_single_explicit_device_required')
    inputs = [existing_file(path) for path in (args.data, args.weights, args.hparams, args.freeze)]
    data_path, weights, hparams_path, freeze_path = inputs
    if weights.suffix != '.pt':
        raise ValueError('trusted_local_pt_required')
    output = outside_checkout(args.output)
    if output.exists():
        raise FileExistsError('refusing_to_overwrite_output')
    hparams = json.loads(hparams_path.read_text(encoding='utf-8'))
    if not isinstance(hparams, dict) or set(hparams) - ALLOWED_HPARAMS:
        raise ValueError('unsupported_hyperparameters')
    if hparams.get('workers', 0) != 0 or hparams.get('cache', False) is not False:
        raise ValueError('candidate_requires_workers0_cache_false')
    data, dataset_files = local_dataset(data_path)
    root = Path(data['path'])
    if output.is_relative_to(root):
        raise ValueError('output_must_be_outside_dataset')
    frozen = verify_freeze(freeze_path)
    required = [data_path, weights, hparams_path, *dataset_files]
    if any(str(path) not in frozen['files'] for path in required):
        raise ValueError('freeze_must_cover_yaml_weights_hparams_and_entire_dataset')
    if args.mode == 'train' and args.split != 'val':
        raise ValueError('training_selection_uses_val_only')
    if args.mode == 'validate' and args.split not in data:
        raise ValueError('requested_split_not_in_yaml')
    output.mkdir(parents=True)
    import yaml
    normalized = output / 'data.yaml'
    normalized.write_text(yaml.safe_dump(data, allow_unicode=True), encoding='utf-8')
    ultralytics, torch = configure_backend(output, args.threads)
    from ultralytics import YOLO
    model = YOLO(str(weights), task='detect')
    if model.task != 'detect':
        raise ValueError('detection_checkpoint_required')
    # Family is an explicit provenance declaration, not inferred from filename.
    # Architecture/provenance verification remains a pre-run acceptance gate.
    write_json(output / 'protocol.json', {
        'family_declared': args.family, 'ultralytics': ultralytics.__version__,
        'torch': torch.__version__, 'device': args.device, 'threads': args.threads,
        'weights_sha256': sha256(weights), 'freeze_sha256': sha256(freeze_path),
        'hparams': hparams, 'nms': True, 'head': 'one-to-many + NMS',
        'mode': args.mode, 'split': args.split, 'private_artifact': True,
    })
    def enforce_budget(context):
        # Upstream select_device() resets threads during lazy setup. Reapply
        # after setup, for training and every validation (including final val).
        torch.set_num_threads(args.threads)
        if args.device == 'cpu' and context.device.type != 'cpu':
            raise RuntimeError('expected_cpu_backend')

    def heartbeat(trainer):
        check_head(trainer.validator)
        write_json(output / 'progress.json', {
            'epoch_completed': min(trainer.epoch + 1, trainer.epochs),
            'total_epochs': trainer.epochs, 'loss': loss_values(trainer.tloss),
            'loss_type': type(trainer.tloss).__name__,
            'torch_threads': torch.get_num_threads(), 'device': str(trainer.device),
        })
    model.add_callback('on_train_start', enforce_budget)
    model.add_callback('on_val_start', enforce_budget)
    model.add_callback('on_fit_epoch_end', heartbeat)
    model.add_callback('on_val_end', check_head)
    common = dict(data=str(normalized), device=args.device, project=str(output),
                  name='run', exist_ok=False, plots=False, nms=True, verbose=False)
    if args.mode == 'train':
        model.train(**{**hparams, **common, 'workers': 0, 'cache': False,
                       'save': True, 'val': True, 'resume': False})
    else:
        metrics = model.val(**common, split=args.split, workers=0,
                            imgsz=hparams.get('imgsz', 512), batch=hparams.get('batch', 4),
                            save_json=False, save_txt=False)
        write_json(output / 'metrics.json', loss_values(metrics.results_dict))
    verify_freeze(freeze_path)
    _, after_files = local_dataset(data_path)
    if set(after_files) != set(dataset_files):
        raise ValueError('dataset_inventory_changed')
    write_json(output / 'completion.json', {'completed': True, 'inputs_unchanged': True})


if __name__ == '__main__':
    main()
